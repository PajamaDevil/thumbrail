import AppKit

struct ClipboardItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
}

/// Keeps a short in-memory history of copied text. Nothing is written to disk.
@MainActor
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    private let pasteboard = NSPasteboard.general
    private let limit = 15
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Password managers mark secrets with these types; never record them.
    private let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    init() {
        lastChangeCount = NSPasteboard.general.changeCount
        // NSPasteboard has no change notification, so poll the cheap change counter.
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
    }

    func clear() { items.removeAll() }

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: skippedTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(text: text), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }
}
